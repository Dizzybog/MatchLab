//! Bounded, conservative Community Learning housekeeping.
//!
//! Only GitHub Actions' daily community threads and signed community-regex
//! review PRs are eligible. Never close maintainer PRs, delete arbitrary parser
//! branches, or discard the durable learning backlog. Run after successful
//! fingerprint/backlog persistence. Dry-run by default.
use crate::github::{quote, GitHub, BOT};
use crate::json::{dumps, Dump, Json};
use crate::obj;
use crate::util::{is_hex, timestamp, Result};
use chrono::{DateTime, Duration, NaiveDate, Utc};
use std::collections::HashSet;

pub const ISSUE_PREFIX: &str = "[community-learning] ";
pub const PR_TITLE: &str = "feat(parser): review high-evidence community regex";
pub const PR_SIGNATURE: &str = "This PR was generated by the trusted Community Learning GitHub Action";
pub const PR_MARKER: &str = "<!-- matchlab-community-regex-review-v1 -->";
pub const KEEP_LABEL: &str = "community-keep-open";
pub const ISSUE_DAYS: i64 = 21;
pub const IDLE_ISSUE_DAYS: i64 = 7;
pub const PR_DAYS: i64 = 30;
pub const BRANCH_GRACE_DAYS: i64 = 7;
pub const ORPHAN_DAYS: i64 = 45;
pub const ORPHAN_IDLE_DAYS: i64 = 30;
pub const LATE_THREAD_AGE_DAYS: i64 = 90;
pub const LATE_THREAD_IDLE_DAYS: i64 = 60;

pub fn age_at_least(value: &Json, now: DateTime<Utc>, days: i64) -> bool {
    timestamp(value).is_some_and(|stamp| stamp <= now - Duration::days(days))
}

fn labels(row: &Json) -> HashSet<String> {
    row.field("labels")
        .as_arr()
        .into_iter()
        .flatten()
        .filter(|item| item.as_obj().is_some())
        .map(|item| dumps(item.field("name"), Dump::DEFAULT))
        .collect()
}

fn has_keep_label(row: &Json) -> bool {
    labels(row).contains(&dumps(&Json::from(KEEP_LABEL), Dump::DEFAULT))
}

fn login(row: &Json) -> Option<&str> {
    row.field("user").field("login").as_str()
}

/// `[community-learning] YYYY-MM-DD` → the date.
pub fn daily_title_date(title: &str) -> Option<NaiveDate> {
    let day = title.strip_prefix(ISSUE_PREFIX)?;
    let bytes = day.as_bytes();
    let shape = bytes.len() == 10
        && bytes.iter().enumerate().all(|(index, byte)| if index == 4 || index == 7 { *byte == b'-' } else { byte.is_ascii_digit() });
    if !shape {
        return None;
    }
    NaiveDate::parse_from_str(day, "%Y-%m-%d").ok()
}

/// Do not close a late-comment thread which the 14-day intake missed.
pub fn daily_issue(row: &Json, now: DateTime<Utc>) -> bool {
    if !row.field("state").str_eq("open") || row.field("pull_request").truthy() {
        return false;
    }
    if login(row) != Some(BOT) || has_keep_label(row) {
        return false;
    }
    let Some(day) = row.field("title").as_str().and_then(daily_title_date) else { return false };
    let (Some(created), Some(updated)) = (timestamp(row.field("created_at")), timestamp(row.field("updated_at"))) else {
        return false;
    };
    if created.date_naive() != day || !age_at_least(row.field("created_at"), now, ISSUE_DAYS) {
        return false;
    }
    if !age_at_least(row.field("updated_at"), now, IDLE_ISSUE_DAYS) {
        return false;
    }
    // A subsequent comment on an older day is not known to have been
    // ingested. Late comments are replayed by the 60-day intake; a very old,
    // long-idle thread is archived rather than kept open indefinitely.
    if row.field("comments").truthy() && updated > created + Duration::days(14) {
        return age_at_least(row.field("created_at"), now, LATE_THREAD_AGE_DAYS)
            && age_at_least(row.field("updated_at"), now, LATE_THREAD_IDLE_DAYS);
    }
    true
}

/// `bot/community-regex-YYYYMMDD[-run[-attempt]]` → the date digits.
pub fn bot_branch_day(name: &str) -> Option<&str> {
    let rest = name.strip_prefix("bot/community-regex-")?;
    let (day, suffix) = rest.split_at_checked(8)?;
    if !day.bytes().all(|byte| byte.is_ascii_digit()) {
        return None;
    }
    let mut parts = 0;
    let mut remaining = suffix;
    while !remaining.is_empty() {
        let tail = remaining.strip_prefix('-')?;
        let digits = tail.bytes().take_while(u8::is_ascii_digit).count();
        if digits == 0 {
            return None;
        }
        remaining = &tail[digits..];
        parts += 1;
    }
    (parts <= 2).then_some(day)
}

pub fn trusted_pr(row: &Json, repo: &str) -> bool {
    let head = row.field("head");
    let base = row.field("base");
    if login(row) != Some(BOT) {
        return false;
    }
    if !row.field("title").str_eq(PR_TITLE) || bot_branch_day(head.field("ref").as_str().unwrap_or_default()).is_none() {
        return false;
    }
    let full_name = head.field("repo").field("full_name").as_str().unwrap_or_default();
    if full_name.to_lowercase() != repo.to_lowercase() {
        return false;
    }
    if !base.field("ref").str_eq("main") || has_keep_label(row) {
        return false;
    }
    let body = row.field("body").as_str().unwrap_or_default();
    body.contains(PR_MARKER) || body.contains(PR_SIGNATURE)
}

pub fn stale_pr(row: &Json, repo: &str, now: DateTime<Utc>) -> bool {
    trusted_pr(row, repo)
        && row.field("state").str_eq("open")
        && !row.field("draft").truthy()
        && !row.field("requested_reviewers").truthy()
        && !row.field("requested_teams").truthy()
        && age_at_least(row.field("created_at"), now, PR_DAYS)
        && age_at_least(row.field("updated_at"), now, PR_DAYS)
}

fn head_sha(row: &Json) -> &Json {
    row.field("head").field("sha")
}

fn commit_sha(branch: &Json) -> &Json {
    branch.field("commit").field("sha")
}

/// Return "review-closed" or "abandoned"; verify commit before deleting.
pub fn stale_branch(branch: &Json, prs: &[Json], repo: &str, now: DateTime<Utc>) -> Option<&'static str> {
    let name = branch.field("name").as_str().unwrap_or_default();
    let day = bot_branch_day(name)?;
    if branch.field("protected").truthy() {
        return None;
    }
    let born = NaiveDate::parse_from_str(day, "%Y%m%d").ok()?.and_hms_opt(0, 0, 0)?.and_utc();
    if born > now || born > now - Duration::days(BRANCH_GRACE_DAYS) {
        return None;
    }
    // A deleted fork or transient GitHub head.repo=None must not let an
    // otherwise associated PR fall through as an "orphan" bot branch.
    let matching: Vec<&Json> = prs.iter().filter(|pr| pr.field("head").field("ref").str_eq(name)).collect();
    if !matching.is_empty() {
        // Never remove the branch of any open PR, or a branch whose latest
        // commit differs from the recorded closed review PR head.
        let unsafe_pr = matching.iter().any(|pr| {
            !pr.field("state").str_eq("closed")
                || !trusted_pr(pr, repo)
                || !age_at_least(pr.field("closed_at"), now, BRANCH_GRACE_DAYS)
                || head_sha(pr) != commit_sha(branch)
        });
        return (!unsafe_pr).then_some("review-closed");
    }
    (born <= now - Duration::days(ORPHAN_DAYS)).then_some("abandoned")
}

/// Preserve already-reviewed proposals for maintainer disposition.
pub fn reviewed_by_human(api: &mut dyn GitHub, number: &Json) -> Result<bool> {
    let reviews = api.pages(&format!("/pulls/{}/reviews", dumps(number, Dump::DEFAULT)))?;
    Ok(reviews.iter().any(|review| {
        matches!(review.field("state").as_str(), Some("APPROVED" | "CHANGES_REQUESTED")) && login(review) != Some(BOT)
    }))
}

pub fn branch_unchanged_and_idle(api: &mut dyn GitHub, branch: &Json, reason: &str, now: DateTime<Utc>) -> Result<bool> {
    let Some(sha) = commit_sha(branch).as_str().filter(|sha| is_hex(sha, 40)) else { return Ok(false) };
    let name = branch.field("name").as_str().unwrap_or_default();
    let current = api.request("GET", &format!("/git/ref/heads/{}", quote(name, "/")), None)?;
    if !current.field("object").field("sha").str_eq(sha) {
        return Ok(false);
    }
    let commit = api.request("GET", &format!("/commits/{sha}"), None)?;
    let details = commit.field("commit");
    let author = details.field("author");
    let committer = details.field("committer");
    if reason == "abandoned" {
        if login_of(commit.field("author")) != Some(BOT) {
            return Ok(false);
        }
        if !author.field("name").str_eq(BOT) && !committer.field("name").str_eq(BOT) {
            return Ok(false);
        }
        return Ok(age_at_least(author.field("date"), now, ORPHAN_IDLE_DAYS)
            && age_at_least(committer.field("date"), now, ORPHAN_IDLE_DAYS));
    }
    Ok(age_at_least(author.field("date"), now, BRANCH_GRACE_DAYS) && age_at_least(committer.field("date"), now, BRANCH_GRACE_DAYS))
}

fn login_of(user: &Json) -> Option<&str> {
    user.field("login").as_str()
}

fn number_route(number: &Json) -> String {
    dumps(number, Dump::DEFAULT)
}

pub fn run(api: &mut dyn GitHub, now: DateTime<Utc>, apply: bool) -> Result<Json> {
    let repo = api.repo().to_owned();
    let issues = api.pages("/issues?state=open&sort=created&direction=desc")?;
    let prs = api.pages("/pulls?state=all&sort=created&direction=desc")?;
    let branches = api.pages("/branches")?;
    let issues_to_close: Vec<&Json> = issues.iter().filter(|issue| daily_issue(issue, now)).collect();
    let mut prs_to_close = Vec::new();
    for pr in &prs {
        if stale_pr(pr, &repo, now) && !reviewed_by_human(api, pr.field("number"))? {
            prs_to_close.push(pr);
        }
    }
    let mut branches_to_delete = Vec::new();
    for branch in &branches {
        if let Some(reason) = stale_branch(branch, &prs, &repo, now)
            && branch_unchanged_and_idle(api, branch, reason, now)? {
                branches_to_delete.push((branch.field("name").as_str().unwrap_or_default().to_owned(), reason));
            }
    }
    let plan = obj! {
        "daily_issues" => Json::Arr(issues_to_close.iter().map(|issue| issue.field("number").clone()).collect()),
        "stale_review_prs" => Json::Arr(prs_to_close.iter().map(|pr| pr.field("number").clone()).collect()),
        "bot_branches" => Json::from_strs(branches_to_delete.iter().map(|(name, _)| name.clone())),
        "apply" => apply,
    };
    println!("{}", dumps(&plan, Dump::DEFAULT.sorted()));
    if !apply {
        return Ok(plan);
    }
    // A PR closed in this run has a seven-day recovery period; branch
    // selection intentionally uses the PRE-mutation PR snapshot.
    for issue in issues_to_close {
        let number = number_route(issue.field("number"));
        let latest = api.request("GET", &format!("/issues/{number}"), None)?;
        // A late comment, label or reopen since listing must prevent closing.
        if latest.field("updated_at") != issue.field("updated_at") || !daily_issue(&latest, now) {
            continue;
        }
        api.request("PATCH", &format!("/issues/{number}"), Some(&obj! {"state" => "closed", "state_reason" => "completed"}))?;
    }
    for pr in prs_to_close {
        let number = number_route(pr.field("number"));
        let latest = api.request("GET", &format!("/pulls/{number}"), None)?;
        // Do not close if another maintainer changed the PR while we planned.
        if latest.field("updated_at") != pr.field("updated_at")
            || head_sha(&latest) != head_sha(pr)
            || !stale_pr(&latest, &repo, now)
            || reviewed_by_human(api, pr.field("number"))?
        {
            continue;
        }
        api.request("PATCH", &format!("/pulls/{number}"), Some(&obj! {"state" => "closed"}))?;
        api.request(
            "POST",
            &format!("/issues/{number}/comments"),
            Some(&obj! {"body" => "Closed by scheduled Community Learning housekeeping after \
                30 days without activity. No parser changes were merged. \
                The review history remains available. Add the \
                `community-keep-open` label to prevent future automatic \
                closure of bot proposals."}),
        )?;
    }
    'branches: for (name, reason) in branches_to_delete {
        let latest = api.request("GET", &format!("/branches/{}", quote(&name, "/")), None)?;
        let Some(original) = branches.iter().find(|branch| branch.field("name").str_eq(&name)) else { continue };
        if latest.field("protected").truthy() || commit_sha(&latest) != commit_sha(original) {
            continue;
        }
        // GitHub's filtered PR query catches an open PR created or reopened
        // since our initial snapshot; do not delete its branch.
        let owner = repo.split('/').next().unwrap_or_default();
        let open = api.request(
            "GET",
            &format!("/pulls?state=open&head={}&per_page=100", quote(&format!("{owner}:{name}"), ":")),
            None,
        )?;
        if open.truthy() {
            continue;
        }
        if reason == "review-closed" {
            let related: Vec<&Json> = prs.iter().filter(|pr| pr.field("head").field("ref").str_eq(&name)).collect();
            if related.is_empty() {
                continue;
            }
            for pr in related {
                let live = api.request("GET", &format!("/pulls/{}", number_route(pr.field("number"))), None)?;
                if !live.field("state").str_eq("closed")
                    || !trusted_pr(&live, &repo)
                    || !age_at_least(live.field("closed_at"), now, BRANCH_GRACE_DAYS)
                    || head_sha(&live) != commit_sha(original)
                {
                    continue 'branches;
                }
            }
        }
        if !branch_unchanged_and_idle(api, &latest, reason, now)? {
            continue;
        }
        api.request("DELETE", &format!("/git/refs/heads/{}", quote(&name, "/")), None)?;
    }
    Ok(plan)
}
