#!/usr/bin/env python3
"""Bounded, conservative Community Learning housekeeping.

Only GitHub Actions' daily community threads and signed community-regex
review PRs are eligible. Never close maintainer PRs, delete arbitrary parser
branches, or discard the durable learning backlog. Run after successful
fingerprint/backlog persistence. Dry-run by default.
"""
import argparse
from datetime import date, datetime, timedelta, timezone
import json
import os
import re
from urllib.error import HTTPError
from urllib.parse import quote
from urllib.request import Request, urlopen

BOT = "github-actions[bot]"
ISSUE_PREFIX = "[community-learning] "
PR_TITLE = "feat(parser): review high-evidence community regex"
PR_SIGNATURE = "This PR was generated by the trusted Community Learning GitHub Action"
PR_MARKER = "<!-- matchlab-community-regex-review-v1 -->"
BOT_BRANCH = re.compile(r"bot/community-regex-(\d{8})(?:-[0-9]+)?\Z")
REPO_PATTERN = re.compile(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+\Z")
KEEP_LABEL = "community-keep-open"
ISSUE_DAYS = 21
IDLE_ISSUE_DAYS = 7
PR_DAYS = 30
BRANCH_GRACE_DAYS = 7
ORPHAN_DAYS = 45
ORPHAN_IDLE_DAYS = 30
LATE_THREAD_AGE_DAYS = 90
LATE_THREAD_IDLE_DAYS = 60


def timestamp(value):
    try:
        return datetime.fromisoformat(value.replace("Z", "+00:00")).astimezone(timezone.utc)
    except (AttributeError, ValueError, TypeError):
        return None


def age_at_least(value, now, days):
    stamp = timestamp(value)
    return stamp is not None and stamp <= now - timedelta(days=days)


def labels(row):
    return {item.get("name") for item in row.get("labels", [])
            if isinstance(item, dict)}


def daily_issue(row, now):
    """Do not close a late-comment thread which the 14-day intake missed."""
    if row.get("state") != "open" or row.get("pull_request"):
        return False
    if row.get("user", {}).get("login") != BOT or KEEP_LABEL in labels(row):
        return False
    title = row.get("title", "")
    if not isinstance(title, str) or not re.fullmatch(
            r"\[community-learning\] \d{4}-\d{2}-\d{2}", title):
        return False
    try:
        day = date.fromisoformat(title[len(ISSUE_PREFIX):])
    except ValueError:
        return False
    created = timestamp(row.get("created_at"))
    updated = timestamp(row.get("updated_at"))
    if not created or not updated:
        return False
    if created.date() != day or not age_at_least(row["created_at"], now, ISSUE_DAYS):
        return False
    if not age_at_least(row["updated_at"], now, IDLE_ISSUE_DAYS):
        return False
    # The importer reads only the previous 14 days of official issue comments.
    # A subsequent comment on an older day is not known to have been ingested,
    # so its issue must not be archived automatically.
    if row.get("comments", 0) and updated > created + timedelta(days=14):
        # Late comments are replayed by the 60-day intake. A very old,
        # long-idle thread is archived rather than kept open indefinitely;
        # closing never deletes the comments or their review history.
        if not (age_at_least(row["created_at"], now, LATE_THREAD_AGE_DAYS)
                and age_at_least(row["updated_at"], now, LATE_THREAD_IDLE_DAYS)):
            return False
    return True


def trusted_pr(row, repo):
    head = row.get("head") or {}
    base = row.get("base") or {}
    if row.get("user", {}).get("login") != BOT:
        return False
    if row.get("title") != PR_TITLE or not BOT_BRANCH.fullmatch(head.get("ref") or ""):
        return False
    if (head.get("repo") or {}).get("full_name", "").lower() != repo.lower():
        return False
    if base.get("ref") != "main" or KEEP_LABEL in labels(row):
        return False
    body = row.get("body") or ""
    return PR_MARKER in body or PR_SIGNATURE in body


def stale_pr(row, repo, now):
    return (trusted_pr(row, repo) and row.get("state") == "open"
            and not row.get("draft") and not row.get("requested_reviewers")
            and not row.get("requested_teams")
            and age_at_least(row.get("created_at"), now, PR_DAYS)
            and age_at_least(row.get("updated_at"), now, PR_DAYS))


def stale_branch(branch, prs, repo, now):
    """Return 'review-closed' or 'abandoned'; verify commit before deleting."""
    name = branch.get("name", "")
    match = BOT_BRANCH.fullmatch(name)
    if not match or branch.get("protected"):
        return None
    try:
        born = datetime.strptime(match.group(1), "%Y%m%d").replace(tzinfo=timezone.utc)
    except ValueError:
        return None
    if born > now or born > now - timedelta(days=BRANCH_GRACE_DAYS):
        return None
    # A deleted fork or transient GitHub head.repo=None must not let an
    # otherwise associated PR fall through as an "orphan" bot branch.
    matching = [p for p in prs if (p.get("head") or {}).get("ref") == name]
    if matching:
        # Never remove the branch of any open PR, or a branch whose latest
        # commit differs from the recorded closed review PR head.
        if any(p.get("state") != "closed" or not trusted_pr(p, repo)
               or not age_at_least(p.get("closed_at"), now, BRANCH_GRACE_DAYS)
               or (p.get("head") or {}).get("sha") != (branch.get("commit") or {}).get("sha")
               for p in matching):
            return None
        return "review-closed"
    if born <= now - timedelta(days=ORPHAN_DAYS):
        return "abandoned"
    return None


class GitHub:
    def __init__(self, repo, token):
        self.repo = repo
        self.token = token

    def request(self, method, route, payload=None):
        url = "https://api.github.com/repos/" + self.repo + route
        data = None if payload is None else json.dumps(payload).encode("utf-8")
        request = Request(url, data=data, method=method, headers={
            "Authorization": "Bearer " + self.token,
            "Accept": "application/vnd.github+json",
            "X-GitHub-Api-Version": "2022-11-28",
            "User-Agent": "matchlab-community-cleanup",
            **({"Content-Type": "application/json"} if data is not None else {}),
        })
        try:
            with urlopen(request, timeout=25) as response:
                raw = response.read()
                return json.loads(raw) if raw else None
        except HTTPError as error:
            raise RuntimeError("GitHub " + method + " " + route +
                               " returned HTTP " + str(error.code)) from error

    def pages(self, path):
        rows = []
        for page in range(1, 101):
            separator = "&" if "?" in path else "?"
            part = self.request("GET", path + separator +
                                "per_page=100&page=" + str(page))
            if not isinstance(part, list):
                raise RuntimeError("GitHub returned an unexpected collection")
            rows.extend(part)
            if len(part) < 100:
                return rows
        raise RuntimeError("GitHub pagination cap reached; refusing partial cleanup")


def reviewed_by_human(api, number):
    """Preserve already-reviewed proposals for maintainer disposition."""
    reviews = api.pages("/pulls/" + str(number) + "/reviews")
    return any(review.get("state") in ("APPROVED", "CHANGES_REQUESTED")
               and review.get("user", {}).get("login") != BOT
               for review in reviews)


def branch_unchanged_and_idle(api, branch, reason, now):
    sha = (branch.get("commit") or {}).get("sha")
    if not isinstance(sha, str) or not re.fullmatch(r"[0-9a-f]{40}", sha):
        return False
    name = branch["name"]
    current = api.request("GET", "/git/ref/heads/" + quote(name, safe="/"))
    if ((current or {}).get("object") or {}).get("sha") != sha:
        return False
    commit = api.request("GET", "/commits/" + sha)
    details = commit.get("commit") or {}
    author = details.get("author") or {}
    committer = details.get("committer") or {}
    if reason == "abandoned":
        if commit.get("author", {}).get("login") != BOT:
            return False
        if author.get("name") != BOT and committer.get("name") != BOT:
            return False
        return (age_at_least(author.get("date"), now, ORPHAN_IDLE_DAYS)
                and age_at_least(committer.get("date"), now, ORPHAN_IDLE_DAYS))
    return (age_at_least(author.get("date"), now, BRANCH_GRACE_DAYS)
            and age_at_least(committer.get("date"), now, BRANCH_GRACE_DAYS))


def run(api, now, apply=False):
    issues = api.pages("/issues?state=open&sort=created&direction=desc")
    prs = api.pages("/pulls?state=all&sort=created&direction=desc")
    branches = api.pages("/branches")
    issues_to_close = [i for i in issues if daily_issue(i, now)]
    prs_to_close = [p for p in prs if stale_pr(p, api.repo, now)
                    and not reviewed_by_human(api, p["number"])]
    branches_to_delete = []
    for branch in branches:
        reason = stale_branch(branch, prs, api.repo, now)
        if reason and branch_unchanged_and_idle(api, branch, reason, now):
            branches_to_delete.append((branch["name"], reason))
    plan = {
        "daily_issues": [i["number"] for i in issues_to_close],
        "stale_review_prs": [p["number"] for p in prs_to_close],
        "bot_branches": [name for name, _ in branches_to_delete],
        "apply": apply,
    }
    print(json.dumps(plan, sort_keys=True))
    if not apply:
        return plan
    # A PR closed in this run has a seven-day recovery period; branch selection
    # intentionally uses the PRE-mutation PR snapshot.
    for issue in issues_to_close:
        number = str(issue["number"])
        latest = api.request("GET", "/issues/" + number)
        # A late comment, label or reopen since listing must prevent closing.
        if (latest.get("updated_at") != issue.get("updated_at")
                or not daily_issue(latest, now)):
            continue
        api.request("PATCH", "/issues/" + number,
                    {"state": "closed", "state_reason": "completed"})
    for pr in prs_to_close:
        number = str(pr["number"])
        latest = api.request("GET", "/pulls/" + number)
        # Do not close if another maintainer changed the PR while we planned.
        if (latest.get("updated_at") != pr.get("updated_at")
                or (latest.get("head") or {}).get("sha") !=
                (pr.get("head") or {}).get("sha")
                or not stale_pr(latest, api.repo, now)
                or reviewed_by_human(api, pr["number"])):
            continue
        api.request("PATCH", "/pulls/" + number, {"state": "closed"})
        api.request("POST", "/issues/" + number + "/comments", {
            "body": ("Closed by scheduled Community Learning housekeeping after "
                     "30 days without activity. No parser changes were merged. "
                     "The review history remains available. Add the "
                     "`community-keep-open` label to prevent future automatic "
                     "closure of bot proposals.")
        })
    for name, reason in branches_to_delete:
        latest = api.request("GET", "/branches/" + quote(name, safe="/"))
        original = next(b for b in branches if b["name"] == name)
        if (latest.get("protected")
                or (latest.get("commit") or {}).get("sha") !=
                (original.get("commit") or {}).get("sha")):
            continue
        # GitHub's filtered PR query catches an open PR created or reopened
        # since our initial snapshot; do not delete its branch.
        owner = api.repo.split("/", 1)[0]
        open_prs = api.request("GET", "/pulls?state=open&head=" +
                               quote(owner + ":" + name, safe=":") + "&per_page=100")
        if open_prs:
            continue
        if reason == "review-closed":
            related = [p for p in prs if (p.get("head") or {}).get("ref") == name]
            if not related:
                continue
            if any((live := api.request("GET", "/pulls/" + str(p["number"])))
                   .get("state") != "closed"
                   or not trusted_pr(live, api.repo)
                   or not age_at_least(live.get("closed_at"), now, BRANCH_GRACE_DAYS)
                   or (live.get("head") or {}).get("sha") !=
                   (original.get("commit") or {}).get("sha")
                   for p in related):
                continue
        if not branch_unchanged_and_idle(api, latest, reason, now):
            continue
        api.request("DELETE", "/git/refs/heads/" + quote(name, safe="/"))
    return plan


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--apply", action="store_true",
                        help="perform actions (default: inspection only)")
    args = parser.parse_args()
    repo = os.environ.get("GH_REPO", "")
    token = os.environ.get("GH_TOKEN", "")
    if not REPO_PATTERN.fullmatch(repo) or not token:
        parser.error("GH_REPO=owner/repo and GH_TOKEN are required")
    run(GitHub(repo, token), datetime.now(timezone.utc), args.apply)


if __name__ == "__main__":
    main()
